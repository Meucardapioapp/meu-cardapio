do $$
begin
  -- Na primeira vez, marca os pedidos antigos que já entraram no
  -- histórico do cliente (para um cancelamento futuro descontar certo).
  if not exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'pedidos' and column_name = 'contabilizado'
  ) then
    alter table public.pedidos add column contabilizado boolean not null default false;
    alter table public.pedidos add column selo_concedido boolean not null default false;

    update public.pedidos
       set contabilizado = true,
           selo_concedido = (payment_method = 'pix' and coalesce(desconto_fidelidade, 0) = 0)
     where coalesce(status, '') not in ('recusado', 'cancelado')
       and (payment_method is distinct from 'pix' or payment_status = 'approved');
  end if;
end $$;

alter table public.pedidos add column if not exists selo_concedido boolean not null default false;

-- ---------------------------------------------------------------------
-- 3. Tabelas (criadas só se não existirem; tipos dos IDs automáticos)
-- ---------------------------------------------------------------------
do $$
declare
  tipo_restaurante text;
  tipo_cliente text;
begin
  select format_type(a.atttypid, a.atttypmod) into tipo_restaurante
    from pg_attribute a
   where a.attrelid = 'public.restaurantes'::regclass and a.attname = 'id';

  select format_type(a.atttypid, a.atttypmod) into tipo_cliente
    from pg_attribute a
   where a.attrelid = 'public.clientes'::regclass and a.attname = 'id';

  -- Configuração do programa de fidelidade de cada restaurante
  execute format($f$
    create table if not exists public.fidelidade (
      id bigint generated by default as identity primary key,
      restaurante_id %s not null references public.restaurantes(id) on delete cascade,
      ativo boolean not null default false,
      pedidos_necessarios integer not null default 10,
      valor_desconto numeric(10,2) not null default 0,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    )$f$, tipo_restaurante);

  -- Selos de cada cliente
  execute format($f$
    create table if not exists public.cliente_fidelidade (
      id bigint generated by default as identity primary key,
      cliente_id %s not null references public.clientes(id) on delete cascade,
      restaurante_id %s not null references public.restaurantes(id) on delete cascade,
      selos integer not null default 0,
      desconto_disponivel boolean not null default false,
      ultimo_resgate timestamptz,
      updated_at timestamptz not null default now()
    )$f$, tipo_cliente, tipo_restaurante);

  -- Cupons de desconto
  execute format($f$
    create table if not exists public.cupons (
      id uuid primary key default gen_random_uuid(),
      restaurante_id %s not null references public.restaurantes(id) on delete cascade,
      codigo text not null check (codigo ~ '^[A-Z0-9_-]{3,30}$'),
      tipo text not null default 'percentual' check (tipo in ('percentual', 'valor')),
      valor numeric(10,2) not null check (valor > 0),
      pedido_minimo numeric(10,2) not null default 0,
      limite_usos integer check (limite_usos is null or limite_usos > 0),
      uso_unico_por_cliente boolean not null default false,
      valido_ate timestamptz,
      ativo boolean not null default true,
      usos integer not null default 0,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      unique (restaurante_id, codigo)
    )$f$, tipo_restaurante);

  -- Guia do painel: quais áreas o dono já visitou
  execute format($f$
    create table if not exists public.painel_guia (
      restaurante_id %s primary key references public.restaurantes(id) on delete cascade,
      passos text[] not null default '{}',
      updated_at timestamptz not null default now()
    )$f$, tipo_restaurante);
end $$;

